const express = require("express");

const router = express.Router();

const {
  register,
  login,
  getMe,
} = require("../controllers/authController");

const {
  authMiddleware,
} = require("../middleware/authMiddleware");


// ============================================================================
// AUTH ROUTES
// ============================================================================


// ---------------------------------------------------------------------------
// REGISTER
// POST /api/auth/register
// ---------------------------------------------------------------------------

router.post(
  "/register",
  register
);


// ---------------------------------------------------------------------------
// LOGIN
// POST /api/auth/login
// ---------------------------------------------------------------------------

router.post(
  "/login",
  login
);


// ---------------------------------------------------------------------------
// CURRENT USER
// GET /api/auth/me
// ---------------------------------------------------------------------------

router.get(
  "/me",
  authMiddleware,
  getMe
);


// ============================================================================
// EXPORT
// ============================================================================

module.exports = router;